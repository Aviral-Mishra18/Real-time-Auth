import React, { useState } from 'react';
import { Modal } from '../common/Modal';
import { useUIStore } from '../../store/uiStore';
import { useWorkspaceStore } from '../../store/workspaceStore';
import { Copy, Check, Share2, ShieldAlert } from 'lucide-react';
import toast from 'react-hot-toast';

export const InviteMembersModal = () => {
  const { isInviteModalOpen, setInviteModalOpen } = useUIStore();
  const { activeWorkspace } = useWorkspaceStore();
  const [copied, setCopied] = useState(false);

  if (!activeWorkspace) return null;

  const inviteCode = activeWorkspace.inviteCode;

  const handleCopyCode = () => {
    navigator.clipboard.writeText(inviteCode);
    setCopied(true);
    toast.success('Invite code copied to clipboard!');
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <Modal
      isOpen={isInviteModalOpen}
      onClose={() => setInviteModalOpen(false)}
      title={`Invite friends to ${activeWorkspace.name}`}
    >
      <div className="space-y-4">
        <p className="text-xs text-slate-400">
          Share this unique invite code with teammates. They can enter it to immediately join this workspace and all public channels.
        </p>

        <div>
          <label className="block text-xs font-semibold text-slate-300 uppercase tracking-wider mb-1.5">
            Workspace Invite Code
          </label>
          <div className="flex items-center gap-2">
            <div className="flex-1 bg-slate-900 border border-slate-700 rounded-xl px-4 py-3 text-base font-mono font-bold tracking-widest text-indigo-400 select-all">
              {inviteCode}
            </div>
            <button
              type="button"
              onClick={handleCopyCode}
              className={`flex items-center gap-1.5 px-4 py-3 rounded-xl text-xs font-bold transition-all shadow-md ${
                copied
                  ? 'bg-emerald-600 text-white'
                  : 'bg-indigo-600 hover:bg-indigo-500 text-white'
              }`}
            >
              {copied ? <Check className="w-4 h-4" /> : <Copy className="w-4 h-4" />}
              <span>{copied ? 'Copied' : 'Copy'}</span>
            </button>
          </div>
        </div>

        <div className="p-3 bg-indigo-950/30 border border-indigo-500/20 rounded-xl flex items-start gap-2.5 text-xs text-indigo-300">
          <Share2 className="w-4 h-4 flex-shrink-0 mt-0.5 text-indigo-400" />
          <span>Invite codes never expire by default unless regenerated by an administrator.</span>
        </div>

        <div className="flex justify-end pt-3 border-t border-slate-800">
          <button
            type="button"
            onClick={() => setInviteModalOpen(false)}
            className="px-5 py-2 rounded-xl text-xs font-bold bg-slate-800 hover:bg-slate-700 text-slate-200 transition-colors"
          >
            Done
          </button>
        </div>
      </div>
    </Modal>
  );
};
